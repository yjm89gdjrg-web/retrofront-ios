import {readFile,writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';

// Inline original CC0 bytes for WKWebView's offline file URL, without file fetch.
const root='src/assets/maps/desert',textures={};
const dataURL=async(file,mime)=>`data:${mime};base64,${(await readFile(file)).toString('base64')}`;
for(const name of ['sandstone','brick','plaster','sand','wood'])textures[name]=await dataURL(`${root}/${name}.jpg`,'image/jpeg');
const modelRoot=`${root}/wooden_crate_02`,model=JSON.parse(await readFile(`${modelRoot}/wooden_crate_02_1k.gltf`,'utf8'));
for(const buffer of model.buffers)buffer.uri=await dataURL(path.join(modelRoot,buffer.uri),'application/octet-stream');
for(const image of model.images)image.uri=await dataURL(path.join(modelRoot,image.uri),'image/jpeg');
await mkdir('src/generated',{recursive:true});
await writeFile('src/generated/desert-assets.js',`// Generated by scripts/convert-map-assets.mjs from the CC0 source assets.\nexport const DESERT_TEXTURES=${JSON.stringify(textures)};\nexport const DESERT_CRATE=${JSON.stringify(model)};\n`);
console.log('Desert CC0 textures and crate embedded for offline WKWebView.');
